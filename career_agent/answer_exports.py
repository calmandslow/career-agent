from __future__ import annotations

import json
from pathlib import Path

from .models import ApplicationState
from .resume_renderer import render_answer_prep_markdown


def write_answer_exports(directory: str | Path, state: ApplicationState) -> dict[str, Path]:
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    pending = state.current_stage == "waiting_for_human_review_interview-answer-coach"
    profile = state.pending_validation_output if pending else state.answer_prep_profile
    if not profile:
        raise RuntimeError("No saved answers to export; an empty formal answer file will not be created")
    if pending:
        payload = {"status": "waiting_for_human_review", "application_id": state.application_id,
                   "validation_issues": state.validation_issues or [],
                   "pending_validation_output": profile}
        json_path = directory / "pending_human_review.json"
        md_path = directory / "pending_interview_answers.md"
        body = "# 待审面试答案（尚未通过验收）\n\n" + render_answer_prep_markdown(profile)
        # Remove only the empty artifacts generated by previous versions.
        old_json = directory / "answer_prep_profile.json"
        if old_json.exists() and json.loads(old_json.read_text(encoding="utf-8")) == {}:
            old_json.unlink()
            old_md = directory / "interview_answers.md"
            if old_md.exists() and old_md.read_text(encoding="utf-8").strip() == "# 面试答案准备\n\n## 表达建议":
                old_md.unlink()
    else:
        payload = profile
        json_path = directory / "answer_prep_profile.json"
        md_path = directory / "interview_answers.md"
        body = render_answer_prep_markdown(profile)
        for name in ("pending_human_review.json", "pending_interview_answers.md"):
            (directory / name).unlink(missing_ok=True)
    json_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    md_path.write_text(body, encoding="utf-8")
    return {"profile": json_path, "readable": md_path}
